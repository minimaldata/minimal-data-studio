import assert from 'node:assert/strict';
import {databaseFolderDropPlan as plan} from '../frontend/database-folders.mjs';
const folders=['A','A/Child','A/Child/Nested','B','B/Child'];
assert.equal(plan('A','B',folders),'B/A');
assert.equal(plan('A/Child','',folders),'Child');
assert.equal(plan('A','A',folders),null);
assert.equal(plan('A','A/Child',folders),null);
assert.equal(plan('A','A/Child/Nested',folders),null);
assert.equal(plan('A/Child','B',folders),null);
assert.equal(plan('A/Child','A',folders),null);
assert.equal(plan('A','',folders),null);
assert.equal(plan('A','Missing',folders),null);
assert.equal(plan('Missing','B',folders),null);
assert.equal(plan('A/Child','B',['A','A/Child','B','B/child']),null);
console.log('Folder drag destinations passed.');
